    private fun table(language: AppLanguage): Map<S, String> = when (language) {
        AppLanguage.AR -> ar
        AppLanguage.EN -> en
        AppLanguage.FR -> fr
        AppLanguage.DE -> de
        AppLanguage.HI -> hi
        AppLanguage.ID -> id
        AppLanguage.JA -> ja
        AppLanguage.KO -> ko
        AppLanguage.PT_BR -> pt_br
        AppLanguage.RU -> ru
        AppLanguage.ES -> es
        AppLanguage.TR -> tr
        AppLanguage.UZ -> uz
    }

    fun t(language: AppLanguage, key: S): String =
        table(language)[key] ?: en[key] ?: key.name

    fun format(language: AppLanguage, key: S, vararg args: Any): String =
        String.format(TimeLocale.locale(language), t(language, key), *args)

}

/** Locale helper kept here so formatting follows the selected app language. */
private object TimeLocale {
    fun locale(language: AppLanguage): java.util.Locale = java.util.Locale.forLanguageTag(language.tag)
}
